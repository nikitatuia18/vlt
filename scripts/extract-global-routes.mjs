// Builds src/components/blocks/Global/routes.data.ts from the route SVGs exported from Figma.
//
// Why: in Figma the routes of the "global" block are dashed strokes animated as "draw-on" (stroke-dasharray).
// The exported SVGs are flat filled outlines of the dashes, so the stroke cannot be animated directly. This script takes
// the centerline of every route (the first point of each dash outline, in drawing order) so that the block can use it as an
// animated mask over the exported picture.
//
// Run: node scripts/extract-global-routes.mjs   (after re-exporting src/assets/global/routes/route-N.svg from Figma)
// The layer boxes and insets below come from `get_design_context` of the node 1110:8942 (layers global__route-N).
import { readFileSync, writeFileSync } from 'node:fs'

// L, T, W, H: box of the layer in the map artboard (px). inset: [top, right, bottom, left] of the picture around the box, in percent.
const layers = [
  { id: 1, L: 493, T: 415.91, W: 483.5, H: 50.874, inset: [-0.98, -0.55, -5.24, -0.55] },
  { id: 2, L: 653.5, T: 563.63, W: 531, H: 207.37, inset: [-0.24, -0.5, -1.29, -0.5] },
  { id: 3, L: 641, T: 481, W: 481, H: 281.825, inset: [-0.95, -0.55, -0.95, -0.55] },
  { id: 4, L: 506.5, T: 482.04, W: 794, H: 180.958, inset: [-0.28, -0.34, -1.47, -0.34] },
  { id: 5, L: 659, T: 638.22, W: 631.5, H: 275.603, inset: [-0.18, -0.42, -0.97, -0.42] },
  { id: 6, L: 405.44, T: 590, W: 169.557, H: 348, inset: [-0.77, -1.57, -0.77, -0.29] },
  { id: 7, L: 359, T: 431.37, W: 597.5, H: 61.126, inset: [-0.82, -0.45, -4.36, -0.45] },
  { id: 8, L: 653.5, T: 504.56, W: 641, H: 390.944, inset: [-0.24, -0.42, -0.68, -0.42] },
  { id: 9, L: 502.25, T: 578, W: 71.745, H: 335.825, inset: [-0.79, -3.72, -0.79, -0.7] },
]

const round = (value, digits = 2) => Number(value.toFixed(digits))
const rows = []

for (const layer of layers) {
  const svg = readFileSync(`src/assets/global/routes/route-${layer.id}.svg`, 'utf8')
  const width = Number(svg.match(/<svg[^>]*\swidth="([\d.]+)"/)[1])
  const height = Number(svg.match(/<svg[^>]*\sheight="([\d.]+)"/)[1])
  const d = svg.match(/\sd="([^"]+)"/)[1]

  // Every dash outline is a subpath that starts with "M x y"; the last two subpaths are the round end dots.
  const starts = [...d.matchAll(/M\s*(-?[\d.]+)[\s,]+(-?[\d.]+)/g)].map((m) => [Number(m[1]), Number(m[2])])
  const dashStarts = starts.slice(0, -2)
  const [startDot, endDot] = starts.slice(-2)
  // The dots are 5.33 px circles that start at their left edge: their centers are 2.667 px to the right.
  const centerline = [[startDot[0] + 2.667, startDot[1]], ...dashStarts, [endDot[0] + 2.667, endDot[1]]]
    .map(([x, y]) => [round(x, 1), round(y, 1)])
    // Drop points that coincide after rounding.
    .filter(([x, y], index, all) => index === 0 || x !== all[index - 1][0] || y !== all[index - 1][1])
  const path = centerline.map(([x, y], index) => `${index === 0 ? 'M' : 'L'}${x} ${y}`).join('')

  const [insetTop, , , insetLeft] = layer.inset
  rows.push({
    id: layer.id,
    left: round(layer.L + (layer.W * insetLeft) / 100),
    top: round(layer.T + (layer.H * insetTop) / 100),
    width,
    height,
    points: centerline.length,
    path,
  })
}

const imports = rows.map((r) => `import route${r.id} from '../../../assets/global/routes/route-${r.id}.svg'`).join('\n')
const body = rows
  .map(
    (r) => `  {
    id: ${r.id},
    src: route${r.id},
    left: ${r.left},
    top: ${r.top},
    width: ${r.width},
    height: ${r.height},
    centerline: '${r.path}',
  },`,
  )
  .join('\n')

writeFileSync(
  'src/components/blocks/Global/routes.data.ts',
  `// GENERATED by scripts/extract-global-routes.mjs from the route SVGs exported from Figma. Do not edit by hand.
${imports}

export type RouteGeometry = {
  /** Number in the Figma layer name \`global__route-{id}\`. */
  id: number
  /** The picture exported from Figma (dashed line, filled outline). */
  src: string
  /** Position and size of the picture in the map artboard (1935 x 1202 px). */
  left: number
  top: number
  width: number
  height: number
  /** Centerline of the route in the coordinates of the picture, in drawing order: used as an animated mask. */
  centerline: string
}

export const routeGeometry: readonly RouteGeometry[] = [
${body}
]
`,
)

for (const r of rows) console.log(`route-${r.id}: ${r.width} x ${r.height} at ${r.left}, ${r.top}; centerline ${r.points} points`)
